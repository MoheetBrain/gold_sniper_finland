#!/usr/bin/env python3
"""v2_04_finalize_report.py — combine v2 posterior x 25kg size term, package probs, restriction gate, write report."""
import json, numpy as np, pandas as pd
from pathlib import Path
ROOT=Path("/Users/mk/AL_THAHAB/gold_sniper"); OUT=ROOT/"data/outputs/full_model_v2"
TOP10=["g2k_01385","g2k_00779","g2k_00780","g2k_02275","g2k_01922","g2k_02274","g2k_01993","g2k_01850","g2k_01386","g2k_01314"]
TOWN={"g2k_01385":"Levi","g2k_00779":"Jeesio","g2k_00780":"Jeesio","g2k_02275":"Pokka","g2k_01922":"Jeesio",
      "g2k_02274":"Pokka","g2k_01993":"Jeesio","g2k_01850":"Jeesio","g2k_01386":"Sirkka","g2k_01314":"Levi"}

term2=json.load(open(ROOT/"data/outputs/full_model_v1/term2_size_calibration.json"))["term2_adopted"]
gate=json.load(open(OUT/"v2_capture_gate.json"))
v2=pd.read_csv(OUT/"monte_carlo_v2_seedavg.csv")
v1=pd.read_csv(ROOT/"data/outputs/monte_carlo_top10.csv")[["cell_id","posterior_mean"]].rename(columns={"posterior_mean":"posterior_v1"})
till=pd.read_parquet(ROOT/"data/processed/till_glacial_v2_features.parquet")[["cell_id","till_evidence","ice_flow_confidence","n_au_5km"]]
mag=pd.read_parquet(ROOT/"data/processed/magnetics_v2_features.parquet")[["cell_id","mag_1vd_score","magnetic_break_score"]]

m=v2[v2.cell_id.isin(TOP10)].merge(v1,on="cell_id",how="left").merge(till,on="cell_id",how="left").merge(mag,on="cell_id",how="left")
m["town"]=m.cell_id.map(TOWN)
m["P_spatial_v2"]=m.posterior_v2_mean
m["P_25kg_v2"]=m.P_spatial_v2*term2
m=m.sort_values("P_25kg_v2",ascending=False).reset_index(drop=True)

# package probability P(>=1 of top-k hosts a >=25kg target)
def pkg(p): p=np.asarray(p); return 1-np.prod(1-p*term2)
ps=m.sort_values("P_spatial_v2",ascending=False).P_spatial_v2.values
pkg3,pkg5,pkg10=pkg(ps[:3]),pkg(ps[:5]),pkg(ps[:10])

cols=["cell_id","town","posterior_v1","P_spatial_v2","P_25kg_v2","posterior_v2_seed_sd","till_evidence","mag_1vd_score","magnetic_break_score","n_au_5km"]
m[cols].to_csv(OUT/"FINAL_FULL_DATA_TOP10_AUDIT.csv",index=False)

def f(x): return f"{x:.4f}"
lines=[]
lines+= ["# FULL-DATA v2 — Top-10 CLGB candidate audit",
"",
"Generated by scripts/v2_01_magnetics.py, v2_02_till_glacial.py, run_monte_carlo_v2.py, v2_03_capture_gate.py.",
"Reuses v1 Monte Carlo math; integrates NEW numeric magnetics + real till geochemistry + glacial back-projection.",
"",
"## Executive verdict",
"**WAIT_FOR_DATA / MANUAL_GEOLOGIST_REVIEW — NOT a BUY.**",
"The full-data model PASSES the hard gate (beats distance-to-fault on top-k capture) and the new data",
"demonstrably improves capture, but (a) three HARD restriction layers remain unscreened (National Parks,",
"Wilderness, Sámi Homeland), and (b) validation rests on only 8 positive labels. No BUY until restrictions clear.",
"",
"## 1. Probability model",
"P(contained Au >= 25 kg) = P(spatial target | evidence)  x  P(>=25 kg | orogenic-gold target)",
f"- Term 2 (size) = {term2:.3f}  (52 Finnish orogenic-gold deposits; only 1 < 25 kg). 25 kg is NOT the binding constraint.",
"- Term 1 (spatial) = v2 Monte Carlo posterior, seed-averaged over seeds 42/7/99 (20k iter each).",
"",
"## 2. Hard gate — top-k capture of 8 known deposits (v2_capture_gate.json)",
"| model | top1% | top5% | top10% | ROC-AUC |",
"|---|---|---|---|---|"]
cap=gate["capture"]; au=gate["roc_auc"]
for k in ["v2 FULL (struct+grav+lith+till+mag)","v2 minus new data (str+grav+lith)","baseline distance-to-fault","v1 model_score (gpkg)"]:
    c=cap[k]; lines.append(f"| {k} | {c['1']:.3f} | {c['5']:.3f} | {c['10']:.3f} | {au[k]:.3f} |")
lines+=[f"", f"**Verdict: {gate['verdict']}.** Adding till+magnetics doubled top-5/10% capture vs structure-only.",
"Caveat: 8 labels only — each capture step ~12.5%; treat as directional, not definitive.",
"",
"## 3. Top-10 — v1 -> v2 and final P(>=25 kg)",
"| rank | cell | town | P_spatial v1 | P_spatial v2 | **P(>=25 kg) v2** | seed_sd | till_ev | mag_1vd | mag_break |",
"|---|---|---|---|---|---|---|---|---|---|"]
for i,r in m.iterrows():
    lines.append(f"| {i+1} | {r.cell_id} | {r.town} | {f(r.posterior_v1)} | {f(r.P_spatial_v2)} | **{f(r.P_25kg_v2)}** | {r.posterior_v2_seed_sd:.4f} | {r.till_evidence:.2f} | {r.mag_1vd_score:.2f} | {r.magnetic_break_score:.2f} |")
lines+=[ "",
f"Package P(>=1 cell hosts a >=25 kg target): top-3 = {pkg3:.3%} | top-5 = {pkg5:.3%} | top-10 = {pkg10:.3%}",
"",
"## 4. What changed and why",
"- g2k_01385 (Levi) remains #1 and rock-stable across seeds — strongest structure + Au/Te till + magnetic low (alteration).",
"- g2k_01314 (Levi) jumped (v1 #10 -> v2 #2): NUMERIC magnetics shows it on a strong magnetic break (break=1.0) + gravity high.",
"- g2k_00779/00780 (Jeesio) hold #3/#4 — strong 5 km till Au anomaly (p98) next to the former Pahtavaara gold mine.",
"- Posteriors are slightly LOWER than v1 at the very top because v2 replaces v1's neutral 0.5 defaults with real",
"  (imperfect) evidence and applies the As/Sb/Bi/W pathfinder-incomplete penalty. This is honest, not pessimistic.",
"",
"## 5. Data ingested (v2)",
"- NUMERIC magnetics: HA_MG_Euref.XYZ (24,414 pts in AOI) -> 500 m grid -> FFT 1VD. magnetic_confidence=HIGH.",
"- Till geochemistry: 5,379 Au + Te samples in AOI; per-cell ECDF-percentile evidence (NOT CLR). As/Sb/Bi/W absent.",
"- Glacial: gf_glacial_lineation_moraine ICE_FLOW_DIRECTION; up-ice back-projection. NOTE: local flow unrecorded in",
"  candidate area -> national-fallback azimuth (284 deg) -> back-projection LOW directional confidence.",
"- Structure/gravity/lithology: reused from v1 audited stack.",
"",
"## 6. Restriction gate (BLOCKS BUY)",
"Present: Natura2000, protected areas, water bodies, groundwater (10 cells clear of these + all TUKES tenure).",
"MISSING (HARD): National Parks, Wilderness areas (eramaa), Sami Homeland. Northern cells (Pokka, N-Sodankyla)",
"are exactly where these can bite. Cannot certify purchase-clear until added. => NO BUY.",
"",
"## 7. Blind spots",
"- 8 positive labels only -> model validation fragile.",
"- Au-in-till is nuggety; As/Sb/Bi/W pathfinder halo unavailable (penalty applied).",
"- Ice-flow direction not locally measured -> back-projection is regional-fallback, low confidence.",
"- Geosoft .grd not GDAL-readable; numeric magnetics taken from the XYZ twin (equivalent data).",
"",
"## 8. Exact next action",
"1) Acquire National Parks + Wilderness + Sami Homeland layers (Metsahallitus / Samediggi) and re-screen 10 cells.",
"2) If clear: ground-truth g2k_01385 + g2k_01314 (Levi) and the g2k_00779/00780 (Jeesio/Pahtavaara) pair.",
"FINAL DECISION: WAIT_FOR_DATA (restrictions) + MANUAL_GEOLOGIST_REVIEW. Not purchase-ready."]
(OUT/"FINAL_FULL_DATA_TOP10_AUDIT.md").write_text("\n".join(lines),encoding="utf-8")
print("[saved] FINAL_FULL_DATA_TOP10_AUDIT.md + .csv")
print("\n=== FINAL v2 P(>=25 kg) top-10 ===")
print(m[["cell_id","town","posterior_v1","P_spatial_v2","P_25kg_v2"]].round(4).to_string(index=False))
print(f"\nPackage P(>=1 >=25kg target): top3={pkg3:.3%} top5={pkg5:.3%} top10={pkg10:.3%}")
